"""
BioTwin.X — Synthetic Clinical Data Engine
===========================================
A physiologically-grounded simulator that produces a **heterogeneous, deeply
asynchronous** cardiometabolic cohort:

* **Static layer** — demographics, anthropometrics, laboratory panels, comorbidity
  flags and a 16-locus genotype panel with true causal effect weights (used to
  build a polygenic risk score and trait-wise vulnerability vectors).
* **Dynamic layer** — six wearable/clinical telemetry streams, each on its own
  physical clock (irregular beat-to-beat ECG, 1-minute PPG, 5-minute CGM,
  30-second sleep epochs) with its own *offset + clock drift*, sensor noise,
  motion artefacts, real-world dropouts (shower, charging, watch removed at
  night) and physiological lags (CGM interstitial lag ~5 min).

Ground truth is generated by a latent physiological state machine, so the
supervised labels (silent ischaemia / glycaemic crash / autonomic arrhythmia,
plus the time-to-event in hours) are causally consistent with the telemetry
that the model observes. The model therefore cannot cheat: it must genuinely
recover the latent event from noisy, asynchronous observations.

Run standalone::

    python synthetic_generator.py --profile demo --persist
"""

