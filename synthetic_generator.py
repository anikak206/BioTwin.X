@dataclass
class PatientProfile:
    """A single synthetic patient — the static half of the digital twin."""

    patient_id: str
    age: float
    sex: str
    bmi: float
    smoking: int
    alcohol_units_wk: float
    sleep_hours: float
    resting_hr: float
    systolic_bp: float
    diastolic_bp: float
    ldl: float
    hdl: float
    triglycerides: float
    hba1c: float
    fasting_glucose: float
    antihypertensive: int
    statin: int
    metformin: int
    family_history_cv: int
    family_history_t2d: int
    prs_raw: float
    prs_raw_z: float
    prs_t2d_z: float
    prs_cvd_z: float
    prs_dys_z: float
    prs_aut_z: float
    primary_event: str
    event_ts: pd.Timestamp | None
    ttx_hours: float
    event_in_horizon: int
    latent_risk: float
    genotypes: dict[str, int]
    sleep_offset_h: float
    respiratory_rate: float
    events: list[tuple[str, str]] = None  # type: ignore[assignment]

    def to_row(self) -> dict:
        row = {k: v for k, v in asdict(self).items()
               if k not in ("genotypes", "events")}
        row["event_ts"] = self.event_ts.isoformat() if self.event_ts is not None else ""
        row.update({f"gt_{rsid}": self.genotypes[rsid] for rsid in self.genotypes})
        return row


class SyntheticCohortGenerator:
    """Generates the static cohort and the asynchronous telemetry streams."""

    def __init__(self, profile: DatasetProfile | str = DEFAULT_PROFILE) -> None:
        self.profile = PROFILES[profile] if isinstance(profile, str) else profile
        self.rng = np.random.default_rng(self.profile.seed)

    # ------------------------------------------------------------------ #
    # Static layer
    # ------------------------------------------------------------------ #
    def generate_cohort(self) -> tuple[pd.DataFrame, list[PatientProfile]]:
        p = self.profile
        n = p.n_patients
        rng = self.rng

        genotypes = simulate_genotypes(n, seed=p.seed)
        prs = compute_prs(genotypes)

        rows: list[dict] = []
        profiles: list[PatientProfile] = []

        for i in range(n):
            pid = f"BTX-{i + 1:04d}"
            age = float(np.clip(rng.normal(52, 14), 22, 88))
            sex = "M" if rng.random() < 0.48 else "F"

            # Anthropometrics — partially driven by the FTO/PPARG risk alleles.
            fto_dosage = int(genotypes.loc[i, "rs9939609"])
            pparg_dosage = int(genotypes.loc[i, "rs1801282"])
            bmi = float(np.clip(rng.normal(27.0, 5.0) + 1.4 * (fto_dosage - 1), 16.0, 45.0))

            smoking = int(rng.random() < (0.14 + 0.0035 * (age - 25)))
            alcohol = float(max(0.0, rng.normal(6, 9) * (0.6 if smoking else 1.0)))
            sleep_hours = float(np.clip(rng.normal(7.1, 1.15), 3.5, 10.5))
            resting_hr = float(np.clip(rng.normal(70, 9) - 0.14 * (age - 40), 44, 105))
            sbp = float(np.clip(rng.normal(124, 15) + 0.55 * (age - 50), 95, 195))
            dbp = float(np.clip(2 * sbp / 3 - rng.normal(0, 6), 55, 118))
            ldl = float(np.clip(rng.normal(116, 30) + 6 * (prs.loc[i, "prs_cvd_z"]), 45, 240))
            hdl = float(np.clip(rng.normal(52, 13) - 3 * (smoking) - 4 * (sex == "M"), 22, 88))
            tg = float(np.clip(rng.normal(148, 78) + 12 * (bmi - 25), 45, 520))
            hba1c = float(np.clip(5.2 + 0.045 * (bmi - 25) + 0.30 * prs.loc[i, "prs_t2d_z"]
                                   + rng.normal(0, 0.32), 4.4, 12.5))
            fpg = float(np.clip(88 + 13 * (hba1c - 5.2) + rng.normal(0, 6), 62, 320))

            antihypertensive = int(sbp > 142)
            statin = int(ldl > 165)
            metformin = int(hba1c > 6.5)
            fh_cv = int(rng.random() < 0.22)
            fh_t2d = int(rng.random() < 0.30 + 0.05 * prs.loc[i, "prs_t2d_z"])

            # ---------------- latent event propensity ------------------ #
            z_t2d = float(prs.loc[i, "prs_t2d_z"])
            z_cvd = float(prs.loc[i, "prs_cvd_z"])
            z_aut = float(prs.loc[i, "prs_aut_z"])

            latent_isch = (
                0.55 * z_cvd + 0.30 * z_t2d + 0.24 * (age - 55) / 10.0
                + 0.30 * (sbp - 125) / 15.0 + 0.22 * smoking
                + 0.20 * (ldl - 115) / 30.0 + 0.15 * fh_cv
                + rng.normal(0, 0.55)
            )
            latent_crash = (
                0.70 * z_t2d + 0.30 * (hba1c - 5.4) / 0.6 + 0.22 * (bmi - 25) / 5.0
                + 0.20 * (fpg - 95) / 25.0 + 0.18 * fh_t2d + 0.30 * metformin
                + rng.normal(0, 0.60)
            )
            latent_arr = (
                0.60 * z_aut + 0.24 * (age - 55) / 10.0 + 0.18 * (bmi - 25) / 5.0
                + 0.15 * (hba1c - 5.4) / 0.6 + rng.normal(0, 0.65)
            )

            p_isch = float(_sigmoid(1.05 * latent_isch - 1.15))
            p_crash = float(_sigmoid(1.10 * latent_crash - 1.25))
            p_arr = float(_sigmoid(1.00 * latent_arr - 1.60))

            has_isch = bool(rng.random() < p_isch)
            has_crash = bool(rng.random() < p_crash)
            has_arr = bool(rng.random() < p_arr)

            # Event timing. Each candidate event type receives one or more
            # timestamps, and **every** candidate is given a full physiological
            # signature in the telemetry (see ``generate_telemetry``) — a label
            # without a cause would be unlearnable noise.
            #
            # Cardiometabolic disease *recurs*: a patient with silent
            # ischaemia typically has several episodes, not one. Modelling
            # recurrence is what makes the window-level supervision dense
            # enough to learn from.
            #
            # Two regimes:
            #   * **imminent** — placed a few hours *after* the end of the
            #     observation window, so that the platform's headline claim
            #     ("alert up to 12 h before onset") is literally true and the
            #     pre-event autonomic signature is visible in the final window.
            #   * **historical** — placed inside the record, providing the
            #     bulk of the supervised training signal.
            total_s = p.seconds
            end_ts = EPOCH_ANCHOR + pd.Timedelta(seconds=total_s)
            candidates: list[tuple[str, pd.Timestamp]] = []
            for label, flag, lead_lo, lead_hi, recur_p, min_gap_h in (
                ("silent_ischemia", has_isch, 1.5, 6.0, 0.55, 14.0),
                ("glycemic_crash", has_crash, 1.0, 4.5, 0.45, 12.0),
                ("autonomic_arrhythmia", has_arr, 0.5, 4.0, 0.40, 10.0),
            ):
                if not flag:
                    continue
                n_ev = 1 + int(rng.random() < recur_p)
                imminent = bool(rng.random() < 0.42)
                hist: list[pd.Timestamp] = []
                for _ in range(max(0, n_ev - (1 if imminent else 0))):
                    hist.append(EPOCH_ANCHOR + pd.Timedelta(
                        seconds=float(rng.uniform(0.03 * total_s, 0.84 * total_s))))
                hist.sort()
                # enforce a minimum separation so two signatures of the same
                # type never overlap and contradict each other
                spaced: list[pd.Timestamp] = []
                for t in hist:
                    if spaced and (t - spaced[-1]).total_seconds() < min_gap_h * 3600:
                        t = spaced[-1] + pd.Timedelta(
                            seconds=min_gap_h * 3600 + float(rng.uniform(600, 3 * 3600)))
                    spaced.append(t)
                times = spaced
                if imminent:
                    lead = float(rng.uniform(lead_lo, lead_hi))
                    t_im = end_ts + pd.Timedelta(hours=lead)
                    # keep every historical event at least `min_gap_h` before it
                    times = [t for t in times
                             if (t_im - t).total_seconds() >= min_gap_h * 3600]
                    times.append(t_im)
                candidates.extend((label, t) for t in times)

            if candidates:
                candidates.sort(key=lambda x: x[1])
                # The *index event* is the imminent one when it exists (that is
                # what the live console is expected to warn about); otherwise
                # the earliest event.
                imminent = [c for c in candidates if c[1] > end_ts]
                primary, event_ts = (imminent[0] if imminent else candidates[0])
                ttx_hours = float((event_ts - end_ts).total_seconds() / 3600.0)
                in_horizon = int(0.0 < ttx_hours <= HORIZON_HOURS)
            else:
                primary, event_ts = "none", None
                ttx_hours = float("inf")
                in_horizon = 0

            latent_risk = float(np.clip(
                0.5 + 0.30 * latent_isch + 0.20 * latent_crash + 0.12 * latent_arr, 0, 1
            ))

            gt = {rsid: int(genotypes.loc[i, rsid]) for rsid in genotypes.columns
                  if rsid != "genotype_seed"}

            prof = PatientProfile(
                patient_id=pid, age=round(age, 1), sex=sex, bmi=round(bmi, 1),
                smoking=smoking, alcohol_units_wk=round(alcohol, 1),
                sleep_hours=round(sleep_hours, 2), resting_hr=round(resting_hr, 1),
                systolic_bp=round(sbp, 1), diastolic_bp=round(dbp, 1),
                ldl=round(ldl, 1), hdl=round(hdl, 1), triglycerides=round(tg, 1),
                hba1c=round(hba1c, 2), fasting_glucose=round(fpg, 1),
                antihypertensive=antihypertensive, statin=statin, metformin=metformin,
                family_history_cv=fh_cv, family_history_t2d=fh_t2d,
                prs_raw=round(float(prs.loc[i, "prs_raw"]), 4),
                prs_raw_z=round(float(prs.loc[i, "prs_raw_z"]), 4),
                prs_t2d_z=round(z_t2d, 4), prs_cvd_z=round(z_cvd, 4),
                prs_dys_z=round(float(prs.loc[i, "prs_dys_z"]), 4),
                prs_aut_z=round(z_aut, 4),
                primary_event=primary, event_ts=event_ts, ttx_hours=ttx_hours,
                event_in_horizon=in_horizon, latent_risk=round(latent_risk, 4),
                genotypes=gt,
                sleep_offset_h=round(float(rng.uniform(-1.2, 1.2)), 3),
                respiratory_rate=round(float(np.clip(rng.normal(14.5, 1.6), 9.0, 22.0)), 2),
                events=[(lbl, ts.isoformat()) for lbl, ts in candidates],
            )
            profiles.append(prof)
            rows.append(prof.to_row())

        static = pd.DataFrame(rows)
        return static, profiles

    # ------------------------------------------------------------------ #
    # Dynamic layer
    # ------------------------------------------------------------------ #
    def generate_telemetry(self, prof: PatientProfile) -> pd.DataFrame:
        """Simulate all asynchronous streams for one patient.

        Returns a *long-format* frame: ``ts, modality, value, quality``.
        """
        p = self.profile
        rng = np.random.default_rng(p.seed + abs(hash(prof.patient_id)) % 100_000)

        # The observation window ends at ``obs_seconds``; the simulator runs a
        # little beyond it so that the *post*-event dynamics of an imminent
        # event are physically consistent, but only the observed prefix is
        # emitted to the pipeline.
        obs_seconds = p.seconds
        n_seconds = obs_seconds + int(6 * 3600)
        t = np.arange(n_seconds, dtype=np.float64)
        base_ts = EPOCH_ANCHOR

        # ---------------- patient-specific baselines ----------------- #
        age_f = (prof.age - 30.0) / 10.0
        is_diabetic = float(prof.hba1c > 6.0 or prof.metformin)
        insulin_resistance = float(np.clip((prof.bmi - 22.0) / 12.0
                                            + (prof.hba1c - 5.2) / 2.5, 0, 3))

        hr_base = 62.0 - 0.18 * age_f + 8.0 * float(prof.smoking) + rng.normal(0, 2.5)
        hrv_base = float(np.exp(np.log(48.0) - 0.115 * age_f - 0.95 * is_diabetic
                                + 0.05 * rng.normal()))
        glu_base = 95.0 + 9.0 * insulin_resistance + rng.normal(0, 3.0)
        spo2_base = 97.4 - 0.05 * age_f
        temp_base = 33.6 + rng.normal(0, 0.12)

        # ---------------- circadian + activity state ------------------ #
        circ = _circadian(t, 0.0)
        asleep = _sleep_window_mask(t, prof.sleep_offset_h)

        # Diurnal activity gate: awake blocks with stochastic bouts.
        day = ~asleep
        act_noise = _ar1(n_seconds, 0.9995, rng)
        activity = np.clip(0.45 + 0.55 * act_noise, 0, 1).astype(np.float32)
        activity = activity * day
        activity = activity * day
        # Exercise bouts
        for _ in range(int(rng.integers(3, 8))):
            start = int(rng.uniform(0, n_seconds - 3600))
            dur = int(rng.uniform(900, 2700))
            activity[start:start + dur] = np.clip(activity[start:start + dur] + 1.4, 0, 2.0)

        # ---------------- event schedule ----------------------------- #
        # EVERY event the patient carries — not just the index one — receives
        # its physiological signature. A label without a cause would be
        # unlearnable noise and would poison the evaluation.
        event_times: dict[str, list[float]] = {}
        for label, ts_iso in (prof.events or []):
            event_times.setdefault(label, []).append(
                (pd.Timestamp(ts_iso) - base_ts).total_seconds())
        for v in event_times.values():
            v.sort()

        # ---------------- heart rate / R-R series -------------------- #
        hr_latent = (
            hr_base
            + 7.5 * circ
            - 3.0 * asleep.astype(np.float64)
            + 34.0 * activity
            + 2.4 * _ar1(n_seconds, 0.9992, rng)
            + 1.1 * _ar1(n_seconds, 0.90, rng)
        )
        hr_latent = np.clip(hr_latent, 34, 205)

        # HRV trajectory (RMSSD proxy) with circadian nadir at 03:00-05:00
        hours_of_day = (t / 3600.0) % 24.0
        nadir = np.exp(-((hours_of_day - 4.0) ** 2) / 6.0)
        hrv_latent = (
            hrv_base
            * (1.0 - 0.30 * nadir)
            * (1.0 - 0.50 * np.clip(activity, 0, 1))
            * (1.0 + 0.16 * circ)
            * np.exp(0.16 * _ar1(n_seconds, 0.9985, rng))
        )
        hrv_latent = np.clip(hrv_latent, 2.0, 220.0)

        # --- Silent ischaemia: progressive nocturnal autonomic withdrawal --- #
        lf_osc = np.zeros(n_seconds)
        for te in event_times.get("silent_ischemia", []):
            pre = (t >= te - 10 * 3600) & (t < te)
            ramp = np.clip((t - (te - 10 * 3600)) / (10 * 3600.0), 0, 1)
            hrv_latent = np.where(pre, hrv_latent * (1.0 - 0.48 * ramp), hrv_latent)
            post = (t >= te) & (t < te + 2.5 * 3600)
            hrv_latent = np.where(post, hrv_latent * 0.55, hrv_latent)
            # Sympathetic LF-band surge (0.08-0.12 Hz) in the run-up
            lf_osc = np.where(pre, np.maximum(lf_osc, 0.055 * ramp), lf_osc)
            hr_latent = np.where(pre, hr_latent + 9.0 * ramp, hr_latent)
            hr_latent = np.where(post, hr_latent - 5.0, hr_latent)

        # --- Glycaemic crash: an 8-hour drift is the observable precursor --- #
        glu_drift = np.zeros(n_seconds)
        for tc in event_times.get("glycemic_crash", []):
            pre = (t >= tc - 8.0 * 3600) & (t < tc - 600)
            ramp = np.clip((t - (tc - 8.0 * 3600)) / (8.0 * 3600.0), 0, 1)
            glu_drift = glu_drift + np.where(pre, -34.0 * ramp, 0.0)
            drop = (t >= tc - 600) & (t < tc + 900)
            fall = -46.0 * np.clip((t - (tc - 600)) / 600.0, 0, 1)
            recover = (t >= tc + 900) & (t < tc + 3 * 3600)
            glu_drift = glu_drift + np.where(drop, fall, 0.0)
            glu_drift = glu_drift + np.where(recover, 30.0 * np.clip(1 - (t - tc - 900) / (2.1 * 3600), 0, 1), 0.0)

        # --- Autonomic arrhythmia: ectopic beat clustering --- #
        ectopic = np.zeros(n_seconds, dtype=bool)
        for ta in event_times.get("autonomic_arrhythmia", []):
            for _ in range(int(rng.integers(8, 16))):
                centre = ta + rng.uniform(-6 * 3600, 2 * 3600)
                width = rng.uniform(900, 3600)
                ectopic |= np.abs(t - centre) < width
        if not event_times.get("autonomic_arrhythmia"):
            ectopic |= rng.random(n_seconds) < 0.00012

        # ---------------- R-R interval series (beat-to-beat) --------- #
        # Beats are irregularly spaced in time -> timestamps are cumulative.
        hr_eff = np.clip(hr_latent, 36, 200)
        rr_mean = 60000.0 / hr_eff
        rr = rr_mean.copy()
        # Respiratory sinus arrhythmia (RSA) couples respiration into RR
        resp_phase = 2 * np.pi * (prof.respiratory_rate / 60.0) * t + rng.uniform(0, 6.28)
        rsa_depth = 0.028 * np.clip(hrv_latent / 45.0, 0.15, 2.2)
        rr = rr * (1.0 + rsa_depth * np.sin(resp_phase))
        # LF-band sympathetic component
        rr = rr * (1.0 + lf_osc * 0.5)
        # Beat-to-beat noise
        rr = rr * np.exp(0.018 * _ar1(n_seconds, 0.55, rng) + 0.010 * rng.standard_normal(n_seconds))
        # Ectopy: premature beats + compensatory pause
        rr = np.where(ectopic, rr * rng.choice([0.42, 1.55], size=n_seconds), rr)

        rr = np.clip(rr, 220.0, 2200.0)
        beat_dt = rr / 1000.0
        beat_ts = base_ts + pd.to_timedelta(np.cumsum(beat_dt), unit="s")
        # Trim to the record window
        keep = (beat_ts >= base_ts) & (beat_ts <= base_ts + pd.Timedelta(seconds=n_seconds))
        beat_ts = beat_ts[keep]
        rr = rr[keep]

        # ---------------- glucose ------------------------------------- #
        glu = glu_base + 11.0 * circ + glu_drift
        # Meals
        meals_per_day = 3 + int(rng.random() < 0.35)
        meal_amp = 32.0 + 38.0 * insulin_resistance + rng.normal(0, 6)
        for day_i in range(p.days):
            for m in range(meals_per_day):
                hour = [8.0, 13.0, 19.5][m % 3] + rng.normal(0, 0.7)
                meal_t = day_i * 86400.0 + hour * 3600.0
                if meal_t > n_seconds:
                    continue
                amp = meal_amp * float(np.clip(rng.normal(1.0, 0.22), 0.35, 1.9))
                dt = t - meal_t
                glu = glu + np.where(dt >= 0, amp * np.exp(-dt / (3600.0 * 2.4)), 0.0)
        glu = glu + 4.0 * _ar1(n_seconds, 0.998, rng)
        glu = np.clip(glu, 28, 420)

        # ---------------- spo2 / temp ---------------------------------- #
        spo2 = (spo2_base + 0.45 * _ar1(n_seconds, 0.99, rng)
                - 0.8 * np.clip(activity - 0.6, 0, 1.4)
                - 1.4 * asleep.astype(np.float64))
        spo2 = np.clip(spo2, 78, 100)
        temp = temp_base + 0.55 * circ - 0.25 * asleep + 0.06 * _ar1(n_seconds, 0.995, rng)

        # ---------------- sleep staging (30 s epochs) ----------------- #
        epoch_s = p.sleep_epoch_s
        n_epochs = int(n_seconds // epoch_s)
        sleep_stage = np.zeros(n_epochs, dtype=np.int8)
        epoch_t = np.arange(n_epochs) * epoch_s
        in_sleep = _sleep_window_mask(epoch_t, prof.sleep_offset_h)
        cycle_pos = np.zeros(n_epochs)
        cycle_len = int(90 * 60 / epoch_s)
        cycle_pos = (np.arange(n_epochs) % cycle_len) / cycle_len
        stage = np.where(cycle_pos < 0.28, 2, np.where(cycle_pos < 0.50, 3,
                       np.where(cycle_pos < 0.62, 4, 2))).astype(np.int8)
        frag = rng.random(n_epochs) < (0.012 + 0.02 * (prof.age - 45) / 20.0)
        stage = np.where(frag & (stage > 0), 0, stage)
        sleep_stage = np.where(in_sleep, stage, 0).astype(np.int8)

        # ---------------- assemble long table ------------------------- #
        frames: list[pd.DataFrame] = []

        def clock_skew(ts: pd.Series, offset_s: float, drift_ppm: float) -> pd.Series:
            """Independent device clock: constant offset + linear drift."""
            elapsed = (ts - base_ts).dt.total_seconds().to_numpy()
            return ts + pd.to_timedelta(offset_s + drift_ppm * 1e-6 * elapsed, unit="s")

        def emit(ts: pd.Series, modality: str, values: np.ndarray,
                 noise: float = 0.0, offset: float = 0.0, drift: float = 0.0,
                 quality_p: float = 0.02, phys_lag_s: float = 0.0) -> None:
            vals = np.asarray(values, dtype=np.float64).copy()
            if noise > 0:
                vals = vals + rng.normal(0, noise, size=vals.shape)
            q = np.ones(vals.shape, dtype=np.int8)
            bad = rng.random(vals.shape) < quality_p
            if noise > 0:
                vals = np.where(bad, vals + rng.normal(0, noise * 6, size=vals.shape), vals)
            q = np.where(bad, 0, 1).astype(np.int8)
            out = pd.DataFrame({"ts": ts.to_numpy(), "modality": modality,
                                "value": vals.astype(np.float32), "quality": q})
            out["ts"] = clock_skew(out["ts"], offset, drift)
            if phys_lag_s:
                out["ts"] = out["ts"] + pd.Timedelta(seconds=phys_lag_s)
            frames.append(out)

        # --- ECG beat series (irregular timestamps) --- #
        frames.append(pd.DataFrame({"ts": beat_ts, "modality": "ecg_rr",
                                    "value": rr.astype(np.float32), "quality": 1}))

        # --- PPG (watch removed at night -> realistic missingness) --- #
        ppg_idx = np.arange(0, n_seconds, p.ppg_period_s)
        ppg_ts = base_ts + pd.to_timedelta(ppg_idx, unit="s")
        ppg_hr = hr_latent[ppg_idx] + rng.normal(0, 2.2, size=ppg_idx.size)
        # device-reported RMSSD, biased + noisy relative to the true signal
        ppg_rmssd = hrv_latent[ppg_idx] * (1.0 + 0.12 * rng.standard_normal(ppg_idx.size)) \
            + rng.normal(0, 4.0, size=ppg_idx.size)
        ppg_rmssd = np.clip(ppg_rmssd, 1.0, 250.0)
        emit(pd.Series(ppg_ts), "ppg_hr", ppg_hr, noise=1.6, offset=rng.uniform(-90, 90),
             drift=rng.uniform(-40, 40), quality_p=0.05)
        emit(pd.Series(ppg_ts), "ppg_rmssd", ppg_rmssd, noise=2.5, offset=rng.uniform(-90, 90),
             drift=rng.uniform(-40, 40), quality_p=0.05)

        # --- CGM (5 min cadence, ~5 min physiological sensor lag) --- #
        cgm_idx = np.arange(0, n_seconds, p.cgm_period_s)
        cgm_ts = base_ts + pd.to_timedelta(cgm_idx, unit="s")
        cgm = glu[cgm_idx] + rng.normal(0, 2.6, size=cgm_idx.size)
        cgm = np.clip(cgm, 25, 430)
        emit(pd.Series(cgm_ts), "cgm_glucose", cgm, noise=1.2, offset=rng.uniform(-240, 240),
             drift=rng.uniform(-60, 60), quality_p=0.015, phys_lag_s=300.0)

        # --- SpO2 --- #
        sp_idx = np.arange(0, n_seconds, p.spo2_period_s)
        sp_ts = base_ts + pd.to_timedelta(sp_idx, unit="s")
        emit(pd.Series(sp_ts), "spo2", spo2[sp_idx], noise=0.5, offset=rng.uniform(-30, 30),
             drift=rng.uniform(-20, 20), quality_p=0.03)

        # --- Skin temperature --- #
        tp_idx = np.arange(0, n_seconds, p.temp_period_s)
        tp_ts = base_ts + pd.to_timedelta(tp_idx, unit="s")
        emit(pd.Series(tp_ts), "skin_temp", temp[tp_idx], noise=0.08,
             offset=rng.uniform(-120, 120), drift=rng.uniform(-30, 30), quality_p=0.02)

        # --- Sleep epochs (night only) --- #
        sl_idx = np.where(in_sleep)[0]
        if len(sl_idx):
            sl_ts = base_ts + pd.to_timedelta(sl_idx * epoch_s, unit="s")
            frames.append(pd.DataFrame({"ts": sl_ts, "modality": "sleep_stage",
                                        "value": sleep_stage[sl_idx].astype(np.float32),
                                        "quality": 1}))

        # --- ST-segment proxy (sparse, only *after* a confirmed ischaemic event) --- #
        # Note this is a strictly post-event signal: it never appears inside
        # the observation window of an imminent event, so it cannot leak the
        # future into the model.
        for te in event_times.get("silent_ischemia", []):
            st_idx = np.arange(max(0, int(te - 7200)), min(n_seconds, int(te + 3600)), 30)
            if len(st_idx):
                st_ts = base_ts + pd.to_timedelta(st_idx, unit="s")
                st_val = np.zeros(st_idx.size)
                after = st_idx >= te
                st_val[after] = 0.12 + 0.05 * rng.random(int(after.sum()))
                frames.append(pd.DataFrame({"ts": st_ts, "modality": "ecg_st",
                                            "value": st_val.astype(np.float32),
                                            "quality": 1}))

        tele = pd.concat(frames, ignore_index=True)
        # Truncate to the observation window: the platform must never see the
        # post-event dynamics it is supposed to *predict*.
        obs_end = base_ts + pd.Timedelta(seconds=obs_seconds)
        tele = tele.loc[tele["ts"] <= obs_end].reset_index(drop=True)
        tele = tele.sort_values("ts", kind="stable").reset_index(drop=True)

        # --- real-world dropouts --- #
        tele = self._apply_dropouts(tele, prof, base_ts, rng)
        # --- duplicate + out-of-order records (realistic stream corruption) --- #
        tele = self._inject_stream_corruption(tele, rng)
        return tele

    # ------------------------------------------------------------------ #
    def _apply_dropouts(self, tele: pd.DataFrame, prof: PatientProfile,
                        base_ts: pd.Timestamp, rng: np.random.Generator) -> pd.DataFrame:
        """Remove segments where the device is genuinely not worn."""
        n_seconds = self.profile.seconds
        keep = np.ones(len(tele), dtype=bool)

        def drop_between(ts: pd.Series, start_s: float, end_s: float) -> None:
            nonlocal keep
            lo = base_ts + pd.Timedelta(seconds=start_s)
            hi = base_ts + pd.Timedelta(seconds=end_s)
            keep &= ~((ts >= lo) & (ts <= hi)).to_numpy()

        # Shower / hygiene gaps on the ECG patch
        for _ in range(int(rng.integers(1, 4))):
            s = float(rng.uniform(0, n_seconds))
            drop_between(tele["ts"], s, s + float(rng.uniform(600, 2700)))
        # Watch is removed overnight (PPG only)
        hours = (tele["ts"] - base_ts).dt.total_seconds() / 3600.0
        sleep_flag = ((hours + prof.sleep_offset_h) % 24 >= SLEEP_START_HOUR) | \
                     ((hours + prof.sleep_offset_h) % 24 < SLEEP_END_HOUR)
        keep &= ~((tele["modality"].isin(["ppg_hr", "ppg_rmssd"])) & sleep_flag).to_numpy()
        # CGM sensor warm-up / brief occlusion
        if rng.random() < 0.45:
            drop_between(tele["ts"], 0.0, float(rng.uniform(900, 5400)))
        # Random patch dropout (battery, skin contact)
        for _ in range(int(rng.integers(1, 5))):
            s = float(rng.uniform(0, n_seconds))
            drop_between(tele["ts"], s, s + float(rng.uniform(300, 1800)))

        return tele.loc[keep].reset_index(drop=True)

    @staticmethod
    def _inject_stream_corruption(tele: pd.DataFrame, rng: np.random.Generator) -> pd.DataFrame:
        """Duplicate ~0.4% of rows and shuffle a tiny fraction out of order."""
        n_dup = max(1, int(0.004 * len(tele)))
        dup_idx = rng.choice(len(tele), size=n_dup, replace=False)
        dups = tele.iloc[dup_idx].copy()
        dups["ts"] = dups["ts"] + pd.to_timedelta(rng.uniform(1, 45, n_dup), unit="s")
        out = pd.concat([tele, dups], ignore_index=True)
        return out.sample(frac=1.0, random_state=int(rng.integers(0, 2**31 - 1))).reset_index(drop=True)

    # ------------------------------------------------------------------ #
    # Orchestration
    # ------------------------------------------------------------------ #
    def generate_all(self, persist: bool = True, verbose: bool = True) -> dict:
        static, profiles = self.generate_cohort()
        static_path = COHORT_DIR / f"{self.profile.name}_patients_static.csv"
        static.to_csv(static_path, index=False)
        dump_panel(ARTIFACT_DIR / "snp_panel.csv")

        # Long-form event table (one row per event) — the supervision signal.
        ev_rows = []
        for prof in profiles:
            for label, ts_iso in (prof.events or []):
                ev_rows.append({"patient_id": prof.patient_id, "event_type": label,
                                "event_ts": ts_iso})
        events_df = pd.DataFrame(ev_rows, columns=["patient_id", "event_type", "event_ts"])
        events_path = COHORT_DIR / f"{self.profile.name}_patient_events.csv"
        events_df.to_csv(events_path, index=False)

        paths: dict[str, str] = {"static": str(static_path), "events": str(events_path)}
        for prof in profiles:
            tele = self.generate_telemetry(prof)
            if persist:
                out = RAW_DIR / f"{self.profile.name}_{prof.patient_id}.parquet"
                tele.to_parquet(out, index=False, compression="zstd")
                paths[prof.patient_id] = str(out)
            if verbose:
                print(f"  • {prof.patient_id}: {len(tele):>9,} telemetry rows | "
                      f"index_event={prof.primary_event} imminent={prof.event_in_horizon}")

        manifest = {
            "profile": asdict(self.profile),
            "n_patients": len(profiles),
            "horizon_hours": HORIZON_HOURS,
            "event_counts": {lab: int((events_df["event_type"] == lab).sum())
                             for lab in list(EVENT_LABELS)},
            "index_event_counts": {lab: int((static["primary_event"] == lab).sum())
                                   for lab in list(EVENT_LABELS) + ["none"]},
            "patients_with_imminent_event": int((static["event_in_horizon"] == 1).sum()),
            "total_events": int(len(events_df)),
            "modality_rows": {m.key: 0 for m in MODALITIES},
            "paths": paths,
        }
        (ARTIFACT_DIR / "dataset_manifest.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8"
        )
        return manifest


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def main(argv: list[str] | None = None) -> int:
    # Windows consoles default to cp1252; make the rich CLI output safe.
    for stream in ("stdout", "stderr"):
        try:
            getattr(sys, stream).reconfigure(encoding="utf-8", errors="replace")
        except Exception:  # pragma: no cover
            pass

    ap = argparse.ArgumentParser(
        prog="synthetic_generator.py",
        description="BioTwin.X synthetic cardiometabolic cohort + asynchronous telemetry generator",
    )
    ap.add_argument("--profile", default=DEFAULT_PROFILE, choices=sorted(PROFILES),
                    help="dataset profile (default: %(default)s)")
    ap.add_argument("--patients", type=int, default=None, help="override cohort size")
    ap.add_argument("--days", type=int, default=None, help="override record length in days")
    ap.add_argument("--no-persist", action="store_true", help="generate in-memory only")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    profile = PROFILES[args.profile]
    if args.patients or args.days:
        profile = DatasetProfile(
            name=f"{profile.name}-custom",
            n_patients=args.patients or profile.n_patients,
            days=args.days or profile.days,
            rr_period_s=profile.rr_period_s,
            ppg_period_s=profile.ppg_period_s,
            cgm_period_s=profile.cgm_period_s,
            spo2_period_s=profile.spo2_period_s,
            temp_period_s=profile.temp_period_s,
            sleep_epoch_s=profile.sleep_epoch_s,
            grid_minutes=profile.grid_minutes,
            horizon_hours=profile.horizon_hours,
            seed=profile.seed,
        )

    gen = SyntheticCohortGenerator(profile)
    if not args.quiet:
        print(f"▸ BioTwin.X synthetic engine — {profile.describe()}")
    manifest = gen.generate_all(persist=not args.no_persist, verbose=not args.quiet)
    if not args.quiet:
        print(f"\n✔ cohort written: {manifest['paths']['static']}")
        print(f"✔ events: {manifest['event_counts']} | total {manifest['total_events']} "
              f"| patients with an imminent event: "
              f"{manifest['patients_with_imminent_event']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
