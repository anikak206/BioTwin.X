# --------------------------------------------------------------------------- #
# Small numerical helpers
# --------------------------------------------------------------------------- #
def _ar1(n: int, phi: float, rng: np.random.Generator) -> np.ndarray:
    """Fast AR(1) / Ornstein-Uhlenbeck noise with **unit stationary variance**.

    The output is scaled by ``sqrt(1 - phi²)`` — the stationary standard
    deviation of an AR(1) driven by unit-variance white noise is
    ``1 / sqrt(1 - phi²)`` — so that the amplitude of a downstream term is
    directly interpretable in standard-deviation units. Without this
    normalisation, a near-unit AR coefficient silently multiplies the signal
    variance by an order of magnitude.
    """
    if n <= 0:
        return np.zeros(0, dtype=np.float32)
    eps = rng.standard_normal(n).astype(np.float32)
    out = lfilter([1.0], [1.0, -phi], eps)
    out[0] = eps[0]
    out = out * np.sqrt(max(1.0 - phi * phi, 1e-6))
    return out.astype(np.float32)


def _sigmoid(x: np.ndarray | float) -> np.ndarray | float:
    return 1.0 / (1.0 + np.exp(-np.clip(x, -60, 60)))


def _circadian(t_seconds: np.ndarray, phase_hours: float = 0.0) -> np.ndarray:
    """Normalised circadian phase in [-1, 1] (peak ~16:00, trough ~04:00)."""
    hours = (t_seconds / 3600.0 + phase_hours) % 24.0
    return np.cos(2.0 * np.pi * (hours - 10.0) / 24.0)


def _sleep_window_mask(t_seconds: np.ndarray, offset_h: float) -> np.ndarray:
    hours = (t_seconds / 3600.0 + offset_h) % 24.0
    return (hours >= SLEEP_START_HOUR) | (hours < SLEEP_END_HOUR)


# --------------------------------------------------------------------------- #
# Patient cohort (static layer)
